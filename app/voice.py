def _plain(text: str) -> str:
    return re.sub(r"<[^>]+>", "", text or "")


def check(text: str, banned: list[str] | None = None, story: bool = False, dashes: bool = True) -> list[str]:
    """Найденные штампы и запрещённые автором фразы — пустой список, если текст чистый.
    story=True — текст поста для канала: заодно ищем описание вместо истории (материалы, площади, этажи).
    dashes=False — без правила «одно тире на абзац» (длинное продолжение для сайта с годами 1913–1915)."""
    s = _plain(text)
    hits = [label for rx, label in PATTERNS if rx.search(s)]
    if story:
        hits += [label for rx, label in DESCRIBE if rx.search(s)]
    low = s.lower()
    hits += [f"«{b}»" for b in (banned or []) if b and b.lower() in low]
    for para in (s.split("\n\n") if dashes else []):
        if para.count("—") + para.count("–") > 1:
            hits.append("больше одного тире в абзаце")
            break
    return list(dict.fromkeys(hits))


async def banned() -> list[str]:
    return list(await db.get_setting("banned_phrases", []))


async def add_banned(raw: str) -> list[str]:
    """Добавляет одну или несколько фраз (через ; или с новой строки) → что добавилось."""
    have = await banned()
    new = [p.strip(" «»\"'.,") for p in re.split(r"[;\n]", raw)]
    new = [p for p in new if 2 <= len(p) <= 80 and p.lower() not in (h.lower() for h in have)]
    await db.set_setting("banned_phrases", have + new)
    return new


async def remove_banned(i: int) -> str | None:
    have = await banned()
    if not 0 <= i < len(have):
        return None
    gone = have.pop(i)
    await db.set_setting("banned_phrases", have)
    return gone
